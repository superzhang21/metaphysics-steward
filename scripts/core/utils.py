def get_shishen(day_gan, target_gan):
    """以日干为我，求目标天干的十神。

    同五行同性为比肩、异性为劫财；
    我生者同性为食神、异性为伤官；
    我克者同性为偏财、异性为正财；
    克我者同性为七杀、异性为正官；
    生我者同性为偏印、异性为正印。
    """
    w1 = WUXING[day_gan]
    w2 = WUXING[target_gan]
    y1 = YINYANG[day_gan]
    y2 = YINYANG[target_gan]

    if w1 == w2:
        return "比肩" if y1 == y2 else "劫财"
    if SHENG[w1] == w2:
        return "食神" if y1 == y2 else "伤官"
    if KE[w1] == w2:
        return "偏财" if y1 == y2 else "正财"
    if KE[w2] == w1:
        return "七杀" if y1 == y2 else "正官"
    if SHENG[w2] == w1:
        return "偏印" if y1 == y2 else "正印"
    return ""

def xiantian_to_houtian(num):
    """先天八卦数 -> 后天八卦数（宫位数）。"""
    mapping = {1: 6, 2: 7, 3: 9, 4: 3, 5: 4, 6: 1, 7: 8, 8: 2}
    return mapping.get(num, num)

def get_ying(shi):
    """由世爻位置推算应爻位置：应 = (世 + 2) % 6 + 1。"""
    return (shi + 2) % 6 + 1

def shishen_short(shishen):
    """十神全称 -> 简称（复用 SHISHEN 映射）。"""
    return SHISHEN.get(shishen, shishen)
