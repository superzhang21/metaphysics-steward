def run_row(y, mo, dd, hh, mm, yj, kong, daygz, shi, chuan, typ):
    r = LiurenEngine.from_civil(datetime(y, mo, dd, hh, mm)).analyze()
    errs = []
    if r["yuejiang"] != yj:
        errs.append("月将 %s!=%s" % (r["yuejiang"], yj))
    if "".join(r["kong"]) != kong:
        errs.append("空亡 %s!=%s" % ("".join(r["kong"]), kong))
    if r["day_gan"] + r["day_zhi"] != daygz:
        errs.append("占时日 %s%s!=%s" % (r["day_gan"], r["day_zhi"], daygz))
    if r["hour_zhi"] != shi:
        errs.append("占时支 %s!=%s" % (r["hour_zhi"], shi))
    if r["chuan"] != chuan:
        errs.append("三传 %s!=%s" % (r["chuan"], chuan))
    if typ and r["type"] != typ:
        errs.append("课型 %s!=%s" % (r["type"], typ))
    return r, errs


def main():
    passed = True
    n = 0
    for (y, mo, dd, zs, yj, kong, daygz, shi, chuan, typ, cf, sk) in GOLDEN:
        r, errs = run_row(y, mo, dd, zs * 2, 30, yj, kong, daygz, shi, chuan, typ)
        n += 1
        tag = "%d-%02d-%02d zs=%d" % (y, mo, dd, zs)
        if errs:
            passed = False
            print("FAIL", tag, " | ".join(errs))
            continue
        for i, x in enumerate(cf):
            a = r["sanchuan"][i]
            got = (a["liuqin"], a["gan"], a["zhi"], a["kong"], a["god"])
            if got != x:
                passed = False
                print("FAIL %s 传%d got=%r expect=%r" % (tag, i + 1, got, x))
        got_sk = [(x["up"], x["down"]) for x in r["sike"]]
        if tuple(got_sk) != sk:
            passed = False
            print("FAIL %s 四课 got=%r expect=%r" % (tag, got_sk, sk))
    print("corpus rows: %d" % n)

    for (y, mo, dd, hh, mm, yj, kong, daygz, shi, chuan, typ) in EXTRA:
        r, errs = run_row(y, mo, dd, hh, mm, yj, kong, daygz, shi, chuan, typ)
        tag = "extra %d-%02d-%02d %02d:%02d" % (y, mo, dd, hh, mm)
        if errs:
            passed = False
            print("FAIL", tag, " | ".join(errs))
        else:
            print("OK  ", tag)

    print("\n结果:", "全部通过" if passed else "存在失败")
    sys.exit(0 if passed else 1)


if __name__ == "__main__":
    main()
